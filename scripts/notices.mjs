#!/usr/bin/env node
// REL2: the JavaScript part of precut's licence notices, generated from package-lock.json so it can't drift.
//
//   node scripts/notices.mjs          rewrites resources/licenses/npm-packages.txt and the package table in
//                                     resources/licenses/THIRD-PARTY-NOTICES.md (between the npm markers)
//   node scripts/notices.mjs --check  fails when either is out of date (run before a release)
//
// What ships: every package electron-builder copies into app.asar (the production dependency tree) and every package
// Vite bundles into the interface (the closure of what src/renderer, src/shared and src/preload import, plus
// tailwindcss, whose base styles are in the built CSS). Each package's own licence file is copied unchanged.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lock = JSON.parse(fs.readFileSync(path.join(ROOT, "package-lock.json"), "utf8")).packages;
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
const OUT_TEXT = path.join(ROOT, "resources/licenses/npm-packages.txt");
const NOTICES = path.join(ROOT, "resources/licenses/THIRD-PARTY-NOTICES.md");
const START = "<!-- npm:start (generated by scripts/notices.mjs) -->", END = "<!-- npm:end -->";

function bareImports(dir) {
  const names = new Set();
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const file = path.join(dir, entry.name);
    if (entry.isDirectory()) { for (const n of bareImports(file)) names.add(n); continue; }
    if (!/\.(tsx?|css)$/.test(entry.name)) continue;
    const text = fs.readFileSync(file, "utf8");
    for (const m of text.matchAll(/(?:from\s+|import\s*\(\s*|import\s+|@import\s+)["']([^"'./][^"']*)["']/g)) {
      const spec = m[1];
      if (spec.startsWith("node:") || spec === "electron") continue;
      names.add(spec.startsWith("@") ? spec.split("/").slice(0, 2).join("/") : spec.split("/")[0]);
    }
  }
  return names;
}
const declared = { ...pkg.devDependencies, ...pkg.dependencies };
const roots = new Set(Object.keys(pkg.dependencies ?? {}));
for (const dir of ["src/renderer", "src/shared", "src/preload"]) for (const name of bareImports(path.join(ROOT, dir))) if (declared[name]) roots.add(name);
roots.add("tailwindcss");

// Node-style resolution over the lockfile's install paths.
function resolve(from, name) {
  let base = from;
  for (;;) {
    const key = (base ? `${base}/` : "") + `node_modules/${name}`;
    if (lock[key]) return key;
    if (!base) return null;
    const at = base.lastIndexOf("/node_modules/");
    base = at < 0 ? "" : base.slice(0, at);
  }
}
const shipped = new Map();
const queue = [...roots].map(name => resolve("", name)).filter(Boolean);
while (queue.length) {
  const key = queue.shift();
  if (shipped.has(key)) continue;
  const entry = lock[key];
  if (entry.optional && !fs.existsSync(path.join(ROOT, key))) continue;   // another platform's optional build
  shipped.set(key, entry);
  // Peers are bundled too (BlockNote's Mantine and Tiptap); an optional peer only when it is installed.
  const peers = Object.keys(entry.peerDependencies ?? {}).filter(name => !entry.peerDependenciesMeta?.[name]?.optional || resolve(key, name));
  for (const name of [...Object.keys({ ...entry.dependencies, ...entry.optionalDependencies }), ...peers]) {
    const dep = resolve(key, name);
    if (dep) queue.push(dep);
  }
}
const nameOf = key => key.slice(key.lastIndexOf("node_modules/") + "node_modules/".length);
const licenceFile = dir => {
  try { return fs.readdirSync(dir).filter(f => /^(licen[cs]e|copying|unlicen[cs]e)(\.|-|$)/i.test(f)).sort()[0] ?? null; } catch { return null; }
};
const rows = [...shipped].map(([key, entry]) => {
  const dir = path.join(ROOT, key), name = nameOf(key);
  let meta = {};
  try { meta = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8")); } catch { /* not installed here */ }
  const licence = typeof meta.license === "string" ? meta.license : entry.license ?? "UNKNOWN";
  const file = licenceFile(dir), text = file ? fs.readFileSync(path.join(dir, file), "utf8").trim() : null;
  const copyright = text?.split("\n").map(l => l.trim()).find(l => /^(copyright\s*(\(c\)|©|\d{4})|\(c\)|©)/i.test(l)) ?? "";
  return { name, version: entry.version, licence, text, file, copyright };
}).filter((row, i, all) => all.findIndex(r => r.name === row.name && r.version === row.version) === i)
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const header = `JavaScript packages in precut\n\nEvery package below ships inside precut.app: in app.asar, or bundled into its interface. Each keeps its own licence;\nits licence file follows, copied unchanged from the package. ${rows.length} packages. Generated by scripts/notices.mjs.\n`;
const body = rows.map(r => `${"=".repeat(78)}\n${r.name} ${r.version}\nLicence: ${r.licence}\n${"-".repeat(78)}\n${r.text ?? `No licence file in this package. Its package.json declares ${r.licence}.`}\n`).join("\n");
const text = `${header}\n${body}`;
const counts = Object.entries(rows.reduce((all, r) => ({ ...all, [r.licence]: (all[r.licence] ?? 0) + 1 }), {})).sort((a, b) => b[1] - a[1]);
// The table names holders only; their addresses stay in the full licence texts (npm-packages.txt).
const cell = s => String(s).replace(/<?(?:mailto:)?[\w.%+-]+@[\w.-]+\.[A-Za-z]{2,}>?/g, "").replace(/\(\s*\)|<\s*>/g, "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const table = [START, "",
  `${rows.length} packages. Licence counts: ${counts.map(([l, n]) => `${l} ${n}`).join(", ")}. Each package's full licence file is in \`npm-packages.txt\`.`, "",
  "| Package | Version | Licence | Copyright |", "| --- | --- | --- | --- |",
  ...rows.map(r => `| ${cell(r.name)} | ${r.version} | ${cell(r.licence)} | ${cell(r.copyright || (r.text ? "see licence file" : "no licence file in package"))} |`), "", END].join("\n");

const notices = fs.readFileSync(NOTICES, "utf8");
const a = notices.indexOf(START), b = notices.indexOf(END);
if (a < 0 || b < a) { console.error(`${path.relative(ROOT, NOTICES)} has no npm markers.`); process.exit(1); }
const nextNotices = notices.slice(0, a) + table + notices.slice(b + END.length);
if (process.argv.includes("--check")) {
  const stale = [fs.existsSync(OUT_TEXT) && fs.readFileSync(OUT_TEXT, "utf8") === text ? null : "npm-packages.txt", nextNotices === notices ? null : "THIRD-PARTY-NOTICES.md"].filter(Boolean);
  if (stale.length) { console.error(`Out of date: ${stale.join(", ")}. Run node scripts/notices.mjs.`); process.exit(1); }
  console.log(`Notices current: ${rows.length} packages.`);
} else {
  fs.writeFileSync(OUT_TEXT, text);
  fs.writeFileSync(NOTICES, nextNotices);
  console.log(`Wrote ${rows.length} packages (${(Buffer.byteLength(text) / 1024).toFixed(0)} KB). Roots: ${[...roots].sort().join(", ")}`);
}
